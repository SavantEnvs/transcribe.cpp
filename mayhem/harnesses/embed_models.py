#!/usr/bin/env python3
"""embed_models.py OUT.inc NAME=PATH... -> a C++ table of embedded model bytes."""
import sys

out, pairs = sys.argv[1], sys.argv[2:]
with open(out, "w") as f:
    f.write("// generated by mayhem/harnesses/embed_models.py\n#pragma once\n#include <cstddef>\n#include <cstdint>\n")
    names = []
    for i, p in enumerate(pairs):
        name, path = p.split("=", 1)
        data = open(path, "rb").read()
        f.write("static const uint8_t k_model_%d[] = {\n" % i)
        for j in range(0, len(data), 32):
            f.write(",".join(str(b) for b in data[j:j + 32]) + ",\n")
        f.write("};\n")
        names.append((name, i))
    f.write("struct embedded_model_t { const char * name; const uint8_t * data; size_t size; };\n")
    f.write("static const embedded_model_t k_models[] = {\n")
    for name, i in names:
        f.write('  {"%s", k_model_%d, sizeof(k_model_%d)},\n' % (name, i, i))
    f.write("};\n")
